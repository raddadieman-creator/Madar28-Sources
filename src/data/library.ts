/** رابط ملف الدليل: النسخة المحلية إن رُفعت، وإلا الرابط الرسمي */
export function docFileUrl(d: GuideDoc, page?: number): string | undefined {
  const base = d.localFile ? import.meta.env.BASE_URL + d.localFile : d.officialUrl
  if (!base) return undefined
  return page ? `${base}#page=${page}` : base
}
